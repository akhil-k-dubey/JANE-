"""
Semantic Resurfacer: Background Daemon for Latent Goal Alignment Monitoring.

Runs as a background thread. Every N seconds, it:
1. Takes the current conversational state vector (from the Hebbian manifold)
2. Measures cosine similarity against all Genesis Anchors
3. Detects misalignment: when current actions diverge from original intent
4. Fires a JARVIS-style proactive interrupt to bring the user back to their 'Why'

This operates entirely in 256D vector space. No text scanning, no regex,
no if-else routing — purely geometric divergence detection.
"""

import time
import threading
from typing import Optional, Callable, Any
import torch
import torch.nn.functional as F
from src.utils.logger import get_logger
from src.reasoning_engine.genesis_node import GenesisNodeRegistry, GenesisAnchor

logger = get_logger('semantic_resurfacer')


class SemanticResurfacer:
    """
    Background alignment monitor.
    
    Fires when: cosine_similarity(current_state, genesis_anchor) drops below DIVERGENCE_THRESHOLD
    AND the anchor hasn't fired recently (cooldown to avoid spam).
    
    The alert text is NOT hardcoded — it's generated by the LLM mouth using
    the anchor's raw_intent_text and the current context.
    """
    
    DIVERGENCE_THRESHOLD = 0.35   # below this = misalignment detected
    CHECK_INTERVAL_SEC = 45.0     # check every 45 seconds
    COOLDOWN_SEC = 300.0          # 5 min cooldown per anchor between firings
    
    def __init__(
        self,
        genesis_registry: GenesisNodeRegistry,
        get_current_state_vec: Callable[[], Optional[torch.Tensor]],  # lambda returning current 256D state
        alert_callback: Callable[[float, GenesisAnchor], None],         # called when misalignment detected
        intent_manifold=None
    ):
        self.registry = genesis_registry
        self._get_state = get_current_state_vec
        self._alert_callback = alert_callback
        self._intent_manifold = intent_manifold
        self.active_override: bool = False
        self.suppressed_anchor_ids = set()
        self._stop_event = threading.Event()
        self._thread: Optional[threading.Thread] = None

    def suppress_anchor(self, anchor_id: str):
        """Mutes alerts for a specific anchor and deactivates it in registry."""
        self.suppressed_anchor_ids.add(anchor_id)
        self.registry.deactivate_anchor(anchor_id)

    def unsuppress_anchor(self, anchor_id: str):
        """Unmutes a previously suppressed anchor."""
        self.suppressed_anchor_ids.discard(anchor_id)

    def set_active_override(self, override: bool):
        """Temporarily pauses/resumes resurfacer alerts (e.g. during side tasks)."""
        self.active_override = override
    
    def _check_alignment(self):
        """Single alignment check pass. Core geometric logic."""
        if self.active_override:
            return

        current_vec = self._get_state()
        if current_vec is None:
            return
        
        now = time.time()
        for anchor in self.registry.get_active_anchors():
            if anchor.anchor_id in self.suppressed_anchor_ids or not getattr(anchor, "is_active", True):
                continue

            if (now - anchor.created_at) < 300:
                continue
            
            # Skip if cooldown active
            if now - anchor.last_activated < self.COOLDOWN_SEC:
                continue
            
            sim = anchor.cosine_similarity_to(current_vec)
            
            # Misalignment: current actions are geometrically diverging from genesis intent
            if sim < self.DIVERGENCE_THRESHOLD:
                anchor.last_activated = now
                anchor.activation_count += 1
                self.registry._save_ledger()  # persist updated activation count
                logger.info('Genesis misalignment detected: anchor=%s sim=%.3f', anchor.project_name, sim)
                self._alert_callback(sim, anchor)
    
    def _run_loop(self):
        while not self._stop_event.is_set():
            try:
                self._check_alignment()
            except Exception as e:
                logger.error('SemanticResurfacer error: %s', e, exc_info=True)
            self._stop_event.wait(self.CHECK_INTERVAL_SEC)
    
    def start(self):
        if self._thread and self._thread.is_alive():
            return
        self._stop_event.clear()
        self._thread = threading.Thread(target=self._run_loop, name='JaneSemanticResurfacer', daemon=True)
        self._thread.start()
        logger.info('SemanticResurfacer background daemon started.')
    
    def stop(self, timeout: float = 2.0):
        self._stop_event.set()
        if self._thread and self._thread.is_alive():
            self._thread.join(timeout=timeout)
        self._thread = None
    
    @property
    def is_running(self) -> bool:
        return self._thread is not None and self._thread.is_alive()
